/**
 * Emits the extension descriptor — the generated half of a package's extension identity.
 *
 * Identity (`extension` IRI, version, `requires`, the ontologies the package owns)
 * is declared once in the `tern` manifest and emitted here as a typed constant, so
 * nothing hand-copies an extension IRI into a `.ts` file.  The descriptor is data
 * only: behaviour (`install`, `upgrade`, handlers) stays hand-written in the
 * package's own extension object, which spreads this descriptor for its identity.
 */

import type { LoadedManifest } from "./manifest.js";
import { manifestTargets } from "./manifest.js";

/** Converts an extension IRI to a SCREAMING_SNAKE constant prefix, e.g. urn:sys:ext:labs → LABS. */
function constantPrefix(extensionIri: string): string {
    const last = extensionIri.split(":").filter(Boolean).pop() ?? "extension";
    return last.replace(/[^A-Za-z0-9]+/g, "_").toUpperCase();
}

/** Converts an extension IRI to a camelCase identifier stem, e.g. urn:sys:ext:labs → labs. */
function identifierStem(extensionIri: string): string {
    const last = extensionIri.split(":").filter(Boolean).pop() ?? "extension";
    const cleaned = last.replace(/[^A-Za-z0-9]+/g, " ").trim();
    const [head = "extension", ...rest] = cleaned.split(/\s+/);
    return (
        head.toLowerCase() + rest.map((w) => w[0].toUpperCase() + w.slice(1).toLowerCase()).join("")
    );
}

function literalArray(values: readonly string[]): string {
    if (values.length === 0) {
        return "[]";
    }
    return `[${values.map((v) => JSON.stringify(v)).join(", ")}]`;
}

/**
 * Generates the TypeScript source for a package's extension descriptor.
 */
export function generateExtensionDescriptor(loaded: LoadedManifest): string {
    const { manifest, packageName, version } = loaded;
    const prefix = constantPrefix(manifest.extension);
    const stem = identifierStem(manifest.extension);

    const ontologies: string[] = [];
    for (const target of manifestTargets(manifest)) {
        for (const ext of target.extensions ?? []) {
            if (!ontologies.includes(ext)) {
                ontologies.push(ext);
            }
        }
    }

    const requires = manifest.requires ?? [];

    return `// AUTO-GENERATED by tern-codegen from the "tern" manifest in package.json.
// Do not edit — change the manifest and re-run \`yarn gen\`.

/** IRI identifying this package as a Tern extension. */
export const ${prefix}_EXTENSION_IRI = ${JSON.stringify(manifest.extension)} as const;

/**
 * Static identity for this extension, derived from its manifest.
 *
 * Spread this into the package's hand-written extension object so identity has a
 * single source:
 *
 *     export const ${stem}Extension = {
 *         ...${stem}ExtensionDescriptor,
 *         async install(ctx) { ... },
 *     };
 */
export const ${stem}ExtensionDescriptor = {
    /** Extension IRI — the stable identity used by the host and the marketplace. */
    iri: ${prefix}_EXTENSION_IRI,
    /** npm package name that ships this extension. */
    name: ${JSON.stringify(packageName)},
    /** Package version, used as the extension version. */
    version: ${version === undefined ? "undefined" : JSON.stringify(version)},
    /** Extension IRIs that must be installed before this one. */
    requires: ${literalArray(requires)},
    /** Ontology files this extension owns, relative to the package root. */
    ontologies: ${literalArray(ontologies)},
} as const;

/** Static shape of this extension's generated identity. */
export type ${prefix.charAt(0)}${prefix.slice(1).toLowerCase()}ExtensionDescriptor =
    typeof ${stem}ExtensionDescriptor;
`;
}
